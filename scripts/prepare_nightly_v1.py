"""Create a new synthetic rubric, refusing to replace existing files."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "examples/nightly-v1"


def write(name, value):
    ROOT.mkdir(parents=True, exist_ok=True)
    with (ROOT / name).open("x", encoding="utf-8") as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2)


def case(cid, split, pairs, facts):
    segments = []
    for question, answer in pairs:
        for role, text in (("doctor", question), ("patient", answer)):
            i = len(segments)
            segments.append({"id": f"s{i+1}", "role": role, "text": text, "start": i, "end": i+1})
    write(cid + ".source.json", {"id": cid, "synthetic": True, "text_revision": 1,
          "timing_origin": "synthetic_order_not_audio", "segments": segments})
    write(cid + ".gold.json", {"id": cid, "synthetic": True, "physician_approved": False,
          "facts": [{"id": f"f{i+1}", "meaning": text, "required_sections": sections,
                     "allowed_sections": allowed, "source_segment_ids": evidence}
                    for i, (text, sections, allowed, evidence) in enumerate(facts)]})
    return {"id": cid, "split": split, "source": cid + ".source.json", "gold": cid + ".gold.json"}


